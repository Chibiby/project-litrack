/**
 * The shapes, copy and pure layout rules of the print template every export
 * carries (the School's End of Term Report layout: centred seal, DepEd header
 * lines, title, two info rows, table, signature block, bottom logos).
 *
 * Pure and client-safe on purpose: the printable learners report renders in a
 * client component, and importing these from `sheet-header.ts` (server-only,
 * Prisma) would break the client build. `sheet-header.ts` re-exports them.
 */

/** A DepEd-style "Label: Value" header line (School ID, School Year, ...). */
export type ReportHeaderField = { label: string; value: string };

/**
 * The two names the signature block prints: who prepared the report and the
 * School Head who notes it.
 */
export type ReportFooter = {
  /** The signed-in actor's display name. */
  preparedBy: string;
  /** The school's School Head, earliest-created if a school somehow has more than one. Blank, never a placeholder string, when the school has none on file. */
  notedBy: string;
};

/**
 * What an export is for.
 *
 * - `PRINT` (the default): the full template, laid out to print cleanly on A4.
 * - `RECORDS`: a plain data sheet — no merged cells, no images, no signature
 *   block — so it sorts, filters and re-imports cleanly. Excel only; a PDF is
 *   always the print template.
 */
export type ReportPurpose = "PRINT" | "RECORDS";

export const REPORT_PURPOSES: readonly ReportPurpose[] = ["PRINT", "RECORDS"];

export const DEFAULT_REPORT_PURPOSE: ReportPurpose = "PRINT";

/**
 * Everything the template needs to know about the school and the people on
 * the report, read once per export (`loadReportFrame` in `sheet-header.ts`).
 * Every field is a plain string; an unknown value is `""`, never a
 * placeholder.
 */
export type ReportFrame = {
  schoolName: string;
  schoolIdCode: string;
  region: string;
  division: string;
  district: string;
  address: string;
  schoolYearLabel: string;
  /** The School Head, for "Noted by". Blank when the school has none on file. */
  schoolHeadName: string;
  /** The signed-in actor, for "Prepared by" and "Generated by". */
  preparedBy: string;
};

