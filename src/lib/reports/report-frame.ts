// ---------------------------------------------------------------------------
// Pure layout rules, shared by the Excel and PDF renderers.
// ---------------------------------------------------------------------------

const MONTH_NAMES = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

/**
 * "23 September 2026". Reads the Date's LOCAL calendar fields, so pass a
 * school-local day (`schoolToday()`), never a raw UTC instant.
 */
export function formatReportDate(date: Date): string {
  return `${date.getDate()} ${MONTH_NAMES[date.getMonth()]} ${date.getFullYear()}`;
}

/** A stored value an admin never filled in: blank, or a bracketed prompt like "[Enter region]". */
function clean(value: string | null | undefined): string {
  const v = (value ?? "").trim();
  if (!v) return "";
  if (/^\[.*\]$/.test(v)) return "";
  return v;
}

/** Prefixes `prefix` unless the value already starts with one of `already`. */
function prefixed(value: string, prefix: string, already: RegExp): string {
  return already.test(value) ? value : `${prefix}${value}`;
}

export type TemplateHeaderLine = {
  text: string;
  bold?: boolean;
  size: number;
  /** ARGB. */
  color: string;
};

export const TEMPLATE_INK = "FF172B42";
export const TEMPLATE_BLUE = "FF2362A0";
export const TEMPLATE_NAVY = "FF17365D";
export const TEMPLATE_MUTED = "FF64748B";

/**
 * The centred lines under the seal, in order. A line whose value the school
 * has not filled in is omitted rather than printed as a placeholder.
 */
export function templateHeaderLines(frame: ReportFrame): TemplateHeaderLine[] {
  const lines: TemplateHeaderLine[] = [
    { text: "Republic of the Philippines", size: 11, color: TEMPLATE_INK },
    { text: "DEPARTMENT OF EDUCATION", bold: true, size: 16, color: TEMPLATE_INK },
  ];
  const region = clean(frame.region);
  if (region) {
    lines.push({
      text: prefixed(region, "Region ", /^region\b/i),
      size: 11,
      color: TEMPLATE_BLUE,
    });
  }
  const division = clean(frame.division);
  if (division) {
    lines.push({
      text: prefixed(division, "Schools Division of ", /^(schools\s+)?division\b/i),
      size: 11,
      color: TEMPLATE_BLUE,
    });
  }
  const district = clean(frame.district);
  if (district) {
    lines.push({
      text: prefixed(district, "District: ", /^district\b/i),
      size: 11,
      color: TEMPLATE_BLUE,
    });
  }
  const school = clean(frame.schoolName);
  if (school) lines.push({ text: school, bold: true, size: 12, color: TEMPLATE_INK });
  const address = clean(frame.address);
  if (address) {
    lines.push({ text: `School Address: ${address}`, size: 11, color: TEMPLATE_BLUE });
  }
  return lines;
}

/** "Grade Level: Grade 3    /    Section: A", or the scope label. */
export function formatGradeSectionLine(line: GradeSectionLine | undefined): string {
  if (line?.gradeLevel) {
    return `Grade Level: ${line.gradeLevel}    /    Section: ${line.section || "All Sections"}`;
  }
  return line?.label || "All Classes";
}

/** The two info rows: [School ID, School Year, Report Date] and [grade/section, reporting period]. */
export function templateInfoRows(args: {
  frame: ReportFrame;
  gradeSection?: GradeSectionLine;
  reportingPeriod?: string;
  reportDate: Date;
}): { first: [string, string, string]; second: [string, string] } {
  return {
    first: [
      `School ID: ${clean(args.frame.schoolIdCode) || "—"}`,
      `School Year: ${clean(args.frame.schoolYearLabel) || "—"}`,
      `Report Date: ${formatReportDate(args.reportDate)}`,
    ],
    second: [
      formatGradeSectionLine(args.gradeSection),
      `Reporting Period: ${args.reportingPeriod || `As of ${formatReportDate(args.reportDate)}`}`,
    ],
  };
}

/**
 * Splits `count` columns into contiguous 1-based groups sized by `fractions`
 * (which should sum to 1). Every group gets at least one column when
 * `count >= fractions.length`.
 */
export function splitColumns(count: number, fractions: number[]): [number, number][] {
  const k = fractions.length;
  const out: [number, number][] = [];
  let start = 1;
  let cumulative = 0;
  for (let i = 0; i < k; i++) {
    cumulative += fractions[i]!;
    let end = i === k - 1 ? count : Math.round(count * cumulative);
    end = Math.max(end, start); // at least one column
    end = Math.min(end, count - (k - 1 - i)); // leave one for every later group
    end = Math.max(end, start);
    out.push([start, end]);
    start = end + 1;
  }
  return out;
}

/** The signature block's three groups, with a spacer column between each when there is room. */
export function signatureGroups(count: number): [number, number][] {
  if (count >= 5) {
    const inner = splitColumns(count - 2, [1 / 3, 1 / 3, 1 / 3]);
    return inner.map(([a, b], i) => [a + i, b + i] as [number, number]);
  }
  return splitColumns(count, [1 / 3, 1 / 3, 1 / 3]);
}

/**
 * The fields the printable (HTML) learners report shows at its top, derived
 * from the same frame the spreadsheets use.
 */
export function frameHeaderFields(
  frame: ReportFrame,
  gradeSection: string
): ReportHeaderField[] {
  const fields: ReportHeaderField[] = [
    { label: "School ID", value: clean(frame.schoolIdCode) || "—" },
    { label: "School Name", value: clean(frame.schoolName) || "—" },
  ];
  if (clean(frame.region)) fields.push({ label: "Region", value: clean(frame.region) });
  if (clean(frame.division)) fields.push({ label: "Division", value: clean(frame.division) });
  if (clean(frame.district)) fields.push({ label: "District", value: clean(frame.district) });
  fields.push(
    { label: "School Year", value: clean(frame.schoolYearLabel) || "—" },
    { label: "Grade / Section", value: gradeSection },
    { label: "Prepared by", value: frame.preparedBy }
  );
  return fields;
}

/** The two signature names, in the shape the printable report takes. */
export function frameFooter(frame: ReportFrame): ReportFooter {
  return { preparedBy: frame.preparedBy, notedBy: frame.schoolHeadName };
}
