/**
 * The ONE implementation of the School's End of Term Report print template
 * for Excel, and its plain RECORDS counterpart. Every Excel-producing path —
 * the Reports Hub (`render.ts`), the learner exports, term grades and the
 * Kindergarten checklist — builds a `TemplateSheet` and hands it here, so the
 * frame never has a second, drifting copy.
 *
 * `loadReportFrame` is the only Prisma in this module: three schoolId-pinned
 * reads (School, SchoolYear, the School Head), made once per export.
 */

// Types and copy live in the client-safe `report-frame.ts`; re-exported so
// server callers keep one import.
export {
  SYSTEM_GENERATED_NOTE,
  type GradeSectionLine,
  type ReportFooter,
  type ReportFrame,
  type ReportHeaderField,
  type ReportPurpose,
};

export type LoadReportFrameArgs = {
  schoolId: string;
  /** Pins the School Year row to this id (still scoped to `schoolId`); omitted or null falls back to the school's active year. */
  schoolYearId?: string | null;
  /** The signed-in actor's display name ("Prepared by", "Generated by"). */
  preparedBy: string;
  /** School name the caller already resolved, used if the fresh School read comes back empty. */
  schoolName?: string | null;
};

/**
 * Everything the template prints about the school and its people. Three
 * reads, all pinned to `schoolId`; a school with no School Head on file (mid-
 * onboarding, or between heads) leaves "Noted by" blank rather than guessing.
 */
export async function loadReportFrame(args: LoadReportFrameArgs): Promise<ReportFrame> {
  const [school, schoolYear, schoolHead] = await Promise.all([
    prisma.school.findFirst({
      where: { id: args.schoolId, deletedAt: null },
      select: {
        schoolIdCode: true,
        name: true,
        region: true,
        division: true,
        district: true,
        address: true,
      },
    }),
    prisma.schoolYear.findFirst({
      where: {
        schoolId: args.schoolId,
        ...(args.schoolYearId ? { id: args.schoolYearId } : { isActive: true }),
      },
      select: { label: true },
    }),
    prisma.user.findFirst({
      where: { schoolId: args.schoolId, role: "SCHOOL_HEAD", deletedAt: null },
      orderBy: { createdAt: "asc" },
      select: { fullName: true },
    }),
  ]);

  return {
    schoolName: school?.name ?? args.schoolName ?? "",
    schoolIdCode: school?.schoolIdCode ?? "",
    region: school?.region ?? "",
    division: school?.division ?? "",
    district: school?.district ?? "",
    address: school?.address ?? "",
    schoolYearLabel: schoolYear?.label ?? "",
    schoolHeadName: schoolHead?.fullName ?? "",
    preparedBy: args.preparedBy,
  };
}

export type TemplateCell = string | number | null;

/** One data sheet, in either purpose. */
export type TemplateSheet = {
  /** The report's title: footer line, page footer, RECORDS line 1. */
  reportTitle: string;
  /** The title row's text when it differs from `reportTitle` (a block heading). Printed uppercase. */
  sheetTitle?: string;
  gradeSection?: GradeSectionLine;
  /** "First Term (Aug–Oct)", "2026-08-24 to 2026-08-28", "As of 23 September 2026". */
  reportingPeriod?: string;
  columns: { header: string; width?: number }[];
  rows: TemplateCell[][];
  /** Count / notes lines printed under the table. */
  summary?: string[];
  /** A block's own annotation (SF2 legend), printed with the summary. */
  note?: string;
  /** 0-based row indices drawn bold with a light fill (SF2 totals, sex headers). */
  boldRowIndices?: number[];
  /** Parallel to `rows`: a `true` cell gets the grey "no record" fill. */
  shadedCells?: boolean[][];
  /** Leading columns frozen alongside the header row. */
  freezeColumns?: number;
  /** 0-based index of the name column: left-aligned, at least 28 wide. Defaults to the first column not headed "#". */
  primaryColumn?: number;
};

export type TemplateContext = {
  frame: ReportFrame;
  /** The school-local day the report is generated on (`schoolToday()`). */
  generatedOn: Date;
};

// ---------------------------------------------------------------------------
// Style constants (ARGB).
// ---------------------------------------------------------------------------

const FONT = "Arial";
const HEADER_FILL = "FF17365D";
const INFO_FILL = "FFFFF2CC";
const DATA_FILL = "FFF0F4F8";
const DATA_RULE = "FFCBD5E1";
const TOTAL_FILL = "FFE2E8F0";
const SHADED_FILL = "FFD9D9D9";
const WHITE = "FFFFFFFF";
const RECORDS_HEADER_FILL = "FFE2E8F0";

const DEFAULT_COL_WIDTH = 18;
const EXTRA_COL_WIDTH = 12;
const PRIMARY_MIN_WIDTH = 28;
/** Header, info and signature rows need at least this many columns to lay out. */
const MIN_TEMPLATE_COLUMNS = 3;

const EMU_PER_PX = 9525;
const SEAL_PX = 100;
const SEAL_TOP_PX = 10;
const BOTTOM_LOGO_PX = 78;
const BOTTOM_LOGO_GAP_PX = 8;
const BOTTOM_LOGO_TOP_PX = 4;

function solid(argb: string) {
  return { type: "pattern" as const, pattern: "solid" as const, fgColor: { argb } };
}

function font(size: number, color: string, extra: { bold?: boolean; italic?: boolean } = {}) {
  return { name: FONT, size, color: { argb: color }, ...extra };
}

// ---------------------------------------------------------------------------
// Images: decoded once per process, registered once per workbook.
// ---------------------------------------------------------------------------

type DecodedLogo = { buffer: Buffer; width: number; height: number };

/** Logo bytes decoded once per process, not once per sheet. */
export const TOP_LOGO: DecodedLogo = {
  buffer: Buffer.from(REPORT_TOP_LOGO.base64, "base64"),
  width: SEAL_PX,
  height: SEAL_PX,
};

export const BOTTOM_LOGOS: DecodedLogo[] = REPORT_BOTTOM_LOGOS.map((logo) => ({
  buffer: Buffer.from(logo.base64, "base64"),
  width: Math.round((BOTTOM_LOGO_PX / logo.height) * logo.width),
  height: BOTTOM_LOGO_PX,
}));

/**
 * Each workbook registers the four logo files once and reuses the ids on
 * every sheet, so a 12-month SF2 export embeds four images, not forty-eight.
 */
const workbookLogoIds = new WeakMap<Workbook, { top: number; bottom: number[] }>();

function logoIds(wb: Workbook): { top: number; bottom: number[] } {
  let ids = workbookLogoIds.get(wb);
  if (!ids) {
    // The cast is exceljs's own wart: its declarations open with
    // `declare interface Buffer extends ArrayBuffer {}` (`node_modules/exceljs/index.d.ts:1`),
    // which leaves a real `Buffer` unassignable to the field asking for one.
    const add = (logo: DecodedLogo) =>
      wb.addImage({
        buffer: logo.buffer as unknown as Parameters<Workbook["addImage"]>[0]["buffer"],
        extension: "png",
      });
    ids = { top: add(TOP_LOGO), bottom: BOTTOM_LOGOS.map(add) };
    workbookLogoIds.set(wb, ids);
  }
  return ids;
}

/** Excel draws a column `w` characters wide as `floor(w * 7 + 5)` px. */
function columnPx(width: number): number {
  return Math.floor(width * 7 + 5);
}

/**
 * A fixed-pixel image anchor. ExcelJS's fractional `{ col, row }` anchors
 * convert offsets with their own unit guess, which lands images in the wrong
 * place; the native form states the cell and an EMU offset exactly.
 */
function nativeAnchor(widthsPx: number[], xPx: number, row0: number, yPx: number) {
  let left = 0;
  let col = widthsPx.length - 1;
  let off = 0;
  for (let i = 0; i < widthsPx.length; i++) {
    if (xPx < left + widthsPx[i]!) {
      col = i;
      off = Math.max(0, xPx - left);
      break;
    }
    left += widthsPx[i]!;
  }
  return {
    nativeCol: col,
    nativeColOff: Math.round(off * EMU_PER_PX),
    nativeRow: row0,
    nativeRowOff: Math.round(yPx * EMU_PER_PX),
  } as unknown as { col: number; row: number };
}

// ---------------------------------------------------------------------------
// Column widths.
// ---------------------------------------------------------------------------

function defaultPrimaryColumn(columns: { header: string }[]): number {
  const idx = columns.findIndex((c) => c.header.trim() !== "#");
  return idx === -1 ? 0 : idx;
}

/** Wide enough that the bold header never wraps past three lines. */
function headerMinWidth(header: string): number {
  const words = header.split(/\s+/).filter(Boolean);
  const longest = words.reduce((m, w) => Math.max(m, w.length), 0);
  const perLine = Math.ceil(header.length / 3);
  return Math.ceil(Math.max(longest, perLine) * 1.2) + 1;
}

function templateWidths(sheet: TemplateSheet, templateCols: number): number[] {
  const primary = sheet.primaryColumn ?? defaultPrimaryColumn(sheet.columns);
  return Array.from({ length: templateCols }, (_, i) => {
    const col = sheet.columns[i];
    if (!col) return EXTRA_COL_WIDTH;
    let w = Math.max(col.width ?? DEFAULT_COL_WIDTH, headerMinWidth(col.header));
    if (i === primary) w = Math.max(w, PRIMARY_MIN_WIDTH);
    return w;
  });
}

// ---------------------------------------------------------------------------
// Row helpers.
// ---------------------------------------------------------------------------

type CellStyle = Partial<Pick<Cell, "font" | "fill" | "alignment" | "border">>;

function styleRange(ws: Worksheet, row: number, from: number, to: number, style: CellStyle) {
  for (let c = from; c <= to; c++) {
    const cell = ws.getRow(row).getCell(c);
    if (style.font) cell.font = style.font;
    if (style.fill) cell.fill = style.fill;
    if (style.alignment) cell.alignment = style.alignment;
    if (style.border) cell.border = style.border;
  }
}

/** Writes `text` into `from`, styles the whole span, and merges it when wider than one cell. */
function mergedText(
  ws: Worksheet,
  row: number,
  from: number,
  to: number,
  text: string,
  style: CellStyle
) {
  ws.getRow(row).getCell(from).value = text;
  styleRange(ws, row, from, to, style);
  if (to > from) ws.mergeCells(row, from, row, to);
}

function blankRow(ws: Worksheet, height?: number): number {
  const row = ws.addRow([]);
  if (height) row.height = height;
  return row.number;
}

function colLetter(ws: Worksheet, col: number): string {
  return ws.getColumn(col).letter;
}

/** `&` is Excel's header/footer control character; a literal one is doubled. */
function escapeHeaderFooter(text: string): string {
  return text.replace(/&/g, "&&");
}

/** Rough wrapped-line count for a merged text cell `widthChars` wide. */
function wrappedLines(text: string, widthChars: number): number {
  return Math.max(1, Math.ceil((text.length * 1.1) / Math.max(widthChars, 1)));
}

