/**
 * A plain data sheet: one identifying line, a blank row, the header at row 3,
 * then the rows. No merged cells, no images, no signature block — nothing
 * that stops Excel sorting, filtering or re-importing it.
 */
export function writeRecordsSheet(ws: Worksheet, ctx: TemplateContext, sheet: TemplateSheet): number {
  const title = sheet.sheetTitle ? `${sheet.reportTitle} — ${sheet.sheetTitle}` : sheet.reportTitle;
  const school = ctx.frame.schoolName || "School";
  ws.addRow([
    `${school} — ${title} — generated ${formatLocalDateKey(ctx.generatedOn)} by ${ctx.frame.preparedBy}`,
  ]).font = { bold: true };
  ws.addRow([]);

  const headerRowNum = ws.addRow(sheet.columns.map((c) => c.header)).number;
  styleRange(ws, headerRowNum, 1, sheet.columns.length, {
    font: { bold: true },
    fill: solid(RECORDS_HEADER_FILL),
  });

  const boldRows = new Set(sheet.boldRowIndices ?? []);
  sheet.rows.forEach((values, rowIdx) => {
    const row = ws.addRow(values.map((v) => (v === null ? "" : v)));
    if (boldRows.has(rowIdx)) row.font = { bold: true };
    sheet.shadedCells?.[rowIdx]?.forEach((shaded, c) => {
      if (shaded) row.getCell(c + 1).fill = solid(SHADED_FILL);
    });
  });

  sheet.columns.forEach((c, i) => {
    ws.getColumn(i + 1).width = c.width ?? DEFAULT_COL_WIDTH;
  });

  if (sheet.columns.length > 0) {
    ws.autoFilter = {
      from: { row: headerRowNum, column: 1 },
      to: { row: headerRowNum + sheet.rows.length, column: sheet.columns.length },
    };
  }
  ws.views = [
    { state: "frozen", xSplit: sheet.freezeColumns ?? 0, ySplit: headerRowNum },
  ];
  return headerRowNum;
}

/** Draws `sheet` onto `ws` in the requested purpose. */
export function writeTemplateSheet(
  wb: Workbook,
  ws: Worksheet,
  ctx: TemplateContext,
  sheet: TemplateSheet,
  purpose: ReportPurpose
): number {
  return purpose === "RECORDS"
    ? writeRecordsSheet(ws, ctx, sheet)
    : writePrintSheet(wb, ws, ctx, sheet);
}
