/**
 * Draws one full print-template sheet onto an EMPTY worksheet: seal, header
 * lines, rule, title, info rows, table, summary, signature block, rule,
 * bottom logos with the generated lines, then page setup. Returns the table
 * header's row number.
 */
export function writePrintSheet(
  wb: Workbook,
  ws: Worksheet,
  ctx: TemplateContext,
  sheet: TemplateSheet
): number {
  const n = sheet.columns.length;
  const cols = Math.max(n, MIN_TEMPLATE_COLUMNS);
  const widths = templateWidths(sheet, cols);
  widths.forEach((w, i) => {
    ws.getColumn(i + 1).width = w;
  });
  const widthsPx = widths.map(columnPx);
  const totalChars = widths.reduce((a, b) => a + b, 0);
  const center = { horizontal: "center" as const, vertical: "middle" as const, wrapText: true };
  const left = { horizontal: "left" as const, vertical: "middle" as const, wrapText: true };
  const primary = sheet.primaryColumn ?? defaultPrimaryColumn(sheet.columns);

  // Row 1: the seal, drawn after widths are final so its centre is right.
  blankRow(ws, 90);

  // Rows 2..: the centred header lines.
  for (const line of templateHeaderLines(ctx.frame)) {
    const r = blankRow(ws, 23);
    mergedText(ws, r, 1, cols, line.text, {
      font: font(line.size, line.color, { bold: line.bold }),
      alignment: center,
    });
  }

  // The rule under the header.
  const ruleTop = blankRow(ws, 6);
  styleRange(ws, ruleTop, 1, cols, {
    border: { bottom: { style: "medium", color: { argb: TEMPLATE_NAVY } } },
  });

  // Title.
  const titleRow = blankRow(ws, 30);
  mergedText(ws, titleRow, 1, cols, (sheet.sheetTitle ?? sheet.reportTitle).toUpperCase(), {
    font: font(14, TEMPLATE_INK, { bold: true }),
    alignment: center,
  });
  blankRow(ws);

  // Info rows.
  const info = templateInfoRows({
    frame: ctx.frame,
    gradeSection: sheet.gradeSection,
    reportingPeriod: sheet.reportingPeriod,
    reportDate: ctx.generatedOn,
  });
  const info1 = blankRow(ws, 23);
  splitColumns(cols, [0.4, 0.3, 0.3]).forEach(([a, b], i) => {
    mergedText(ws, info1, a, b, info.first[i]!, {
      font: font(11, TEMPLATE_INK, { bold: true }),
      fill: solid(INFO_FILL),
      alignment: center,
    });
  });
  const info2 = blankRow(ws, 23);
  splitColumns(cols, [0.4, 0.6]).forEach(([a, b], i) => {
    mergedText(ws, info2, a, b, info.second[i]!, {
      font: font(11, TEMPLATE_INK, { bold: true }),
      alignment: center,
    });
  });
  blankRow(ws);

  // Table header.
  const headerRowNum = ws.addRow(sheet.columns.map((c) => c.header)).number;
  const headerRow = ws.getRow(headerRowNum);
  headerRow.height = 40;
  const whiteSide = { style: "thin" as const, color: { argb: WHITE } };
  styleRange(ws, headerRowNum, 1, n, {
    font: font(11, WHITE, { bold: true }),
    fill: solid(HEADER_FILL),
    alignment: center,
    border: { left: whiteSide, right: whiteSide },
  });

  // Data rows.
  const boldRows = new Set(sheet.boldRowIndices ?? []);
  const averageCol = sheet.columns.findIndex((c) => /general average/i.test(c.header));
  const rule = { bottom: { style: "thin" as const, color: { argb: DATA_RULE } } };
  sheet.rows.forEach((values, rowIdx) => {
    const row = ws.addRow(values.map((v) => (v === null ? "" : v)));
    row.height = 22;
    const isBold = boldRows.has(rowIdx);
    for (let c = 1; c <= n; c++) {
      const cell = row.getCell(c);
      const shaded = !isBold && sheet.shadedCells?.[rowIdx]?.[c - 1];
      cell.font = font(11, TEMPLATE_INK, { bold: isBold || c - 1 === averageCol });
      cell.fill = solid(isBold ? TOTAL_FILL : shaded ? SHADED_FILL : DATA_FILL);
      cell.border = rule;
      cell.alignment = {
        horizontal: c - 1 === primary ? "left" : "center",
        vertical: "middle",
      };
      if (typeof cell.value === "number" && Number.isInteger(cell.value)) cell.numFmt = "0";
    }
  });

  // Summary + note.
  const summaryLines = [...(sheet.summary ?? []), ...(sheet.note ? [sheet.note] : [])];
  if (summaryLines.length > 0) {
    blankRow(ws);
    for (const line of summaryLines) {
      const r = blankRow(ws);
      const lines = wrappedLines(line, totalChars);
      if (lines > 1) ws.getRow(r).height = 15 * lines;
      mergedText(ws, r, 1, cols, line, { font: font(11, TEMPLATE_INK), alignment: left });
    }
  }

  // Signature block.
  blankRow(ws);
  blankRow(ws);
  const groups = signatureGroups(cols);
  const labels = ["Prepared by:", "Checked by:", "Noted by:"];
  const names = [ctx.frame.preparedBy, "", ctx.frame.schoolHeadName];
  const labelRow = blankRow(ws, 20);
  groups.forEach(([a, b], i) =>
    mergedText(ws, labelRow, a, b, labels[i]!, {
      font: font(11, TEMPLATE_INK, { bold: true }),
      alignment: center,
    })
  );
  blankRow(ws, 28);
  const nameRow = blankRow(ws, 20);
  groups.forEach(([a, b], i) =>
    mergedText(ws, nameRow, a, b, names[i]!, {
      font: font(11, TEMPLATE_INK, { bold: true }),
      alignment: center,
      border: { bottom: { style: "thin", color: { argb: TEMPLATE_MUTED } } },
    })
  );
  const captionRow = blankRow(ws, 16);
  groups.forEach(([a, b]) =>
    mergedText(ws, captionRow, a, b, SIGNATURE_CAPTION, {
      font: font(9, TEMPLATE_MUTED),
      alignment: center,
    })
  );

  // Rule, then the footer rows.
  blankRow(ws);
  const ruleBottom = blankRow(ws, 6);
  styleRange(ws, ruleBottom, 1, cols, {
    border: { bottom: { style: "thin", color: { argb: TEMPLATE_NAVY } } },
  });

  const logosPx =
    BOTTOM_LOGOS.reduce((sum, l) => sum + l.width, 0) +
    BOTTOM_LOGO_GAP_PX * BOTTOM_LOGOS.length;
  let textStart = cols;
  let edge = 0;
  for (let c = 1; c <= cols; c++) {
    if (edge >= logosPx) {
      textStart = c;
      break;
    }
    edge += widthsPx[c - 1]!;
  }
  textStart = Math.min(cols, Math.max(textStart, Math.floor(cols * 0.4) + 1));
  const footerLines = [
    `LITRACK | ${sheet.reportTitle}`,
    `Generated by ${ctx.frame.preparedBy} on ${formatLocalDateKey(ctx.generatedOn)}`,
    SYSTEM_GENERATED_NOTE,
  ];
  const firstFooterRow = ws.rowCount + 1;
  for (const line of footerLines) {
    const r = blankRow(ws, 22);
    mergedText(ws, r, textStart, cols, line, {
      font: font(9, TEMPLATE_MUTED),
      alignment: { horizontal: "right", vertical: "middle" },
    });
  }
  const lastRow = ws.rowCount;

  // Images, all at fixed pixel sizes.
  const ids = logoIds(wb);
  const tablePx = widthsPx.reduce((a, b) => a + b, 0);
  ws.addImage(ids.top, {
    tl: nativeAnchor(widthsPx, Math.max(0, Math.round(tablePx / 2 - SEAL_PX / 2)), 0, SEAL_TOP_PX),
    ext: { width: TOP_LOGO.width, height: TOP_LOGO.height },
  });
  let x = 0;
  BOTTOM_LOGOS.forEach((logo, i) => {
    ws.addImage(ids.bottom[i]!, {
      tl: nativeAnchor(widthsPx, x, firstFooterRow - 1, BOTTOM_LOGO_TOP_PX),
      ext: { width: logo.width, height: logo.height },
    });
    x += logo.width + BOTTOM_LOGO_GAP_PX;
  });

  // Page setup.
  const lastCol = colLetter(ws, cols);
  ws.pageSetup = {
    ...ws.pageSetup,
    paperSize: 9,
    orientation: n > 6 ? "landscape" : "portrait",
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0,
    horizontalCentered: true,
    showGridLines: false,
    margins: { left: 0.25, right: 0.25, top: 0.3, bottom: 0.3, header: 0.15, footer: 0.15 },
    printArea: `A1:${lastCol}${lastRow}`,
    printTitlesRow: `${headerRowNum}:${headerRowNum}`,
  };
  ws.headerFooter = {
    ...ws.headerFooter,
    oddFooter: `&L LITRACK&C ${escapeHeaderFooter(sheet.reportTitle)}&R Page &P of &N`,
  };
  // No frozen panes on a print sheet: the table header sits ~15 rows down,
  // under the seal and letterhead, and freezing there pins most of a laptop
  // screen. Printing repeats the header via `printTitlesRow` above instead.
  ws.views = [{ state: "normal", showGridLines: false }];

  return headerRowNum;
}

